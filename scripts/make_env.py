#!/usr/bin/env python3
"""Create your local .env file from .env.example, with fresh random passwords and keys.

Usage (from the repository root; needs only Python 3, no packages):
    python scripts/make_env.py            # Windows: py scripts/make_env.py
    python scripts/make_env.py --auth oidc    # keep Keycloak sign-in instead of local dev tokens
    python scripts/make_env.py --force        # replace an existing .env (asks for nothing)

What it does:
- copies .env.example to .env and replaces every "change_me" password with a random one (the
  database password is the same everywhere it appears, so the database and the app agree);
- creates a random signing key for local development tokens (AUTH_DEV_SECRET);
- switches on the lines the example ships commented out, so that `docker compose` also loads the
  dev tools container (docker-compose.dev.yml) and the test database setting is present.

It never prints the secrets, and it refuses to overwrite an existing .env unless you pass --force.
.env is listed in .gitignore and .dockerignore, so it is not committed and not copied into images.
"""

import argparse
import secrets
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER = "change_me_local_only"
# Lines the example ships commented out; they are switched on in the generated file.
OPT_IN_PREFIXES = ("# COMPOSE_PATH_SEPARATOR=", "# COMPOSE_FILE=", "# TEST_DATABASE_URL=")
# The example's header tells you to copy it and replace the placeholders. In the generated file
# that has already been done, so those two lines are swapped for an accurate description.
HEADER_REPLACEMENTS = {
    "# Copy this file to .env": "# Generated by scripts/make_env.py from .env.example; not committed (see .gitignore).",
    "# Never put real passwords or keys in this committed file.": "# It holds real secrets for this machine only: do not share it or paste it into chats.",
}


def new_secret(nbytes: int = 24) -> str:
    """URL-safe random text (letters, digits, - and _), so it is safe inside a database URL."""
    return secrets.token_urlsafe(nbytes)


def build_env(example_text: str, *, auth_mode: str = "dev") -> str:
    if auth_mode not in ("dev", "oidc"):
        raise ValueError("auth_mode must be 'dev' or 'oidc'")
    db_password = new_secret()
    keycloak_password = new_secret()
    dev_signing_key = new_secret(48)

    lines = []
    for line in example_text.splitlines():
        stripped = line.strip()
        for start, replacement in HEADER_REPLACEMENTS.items():
            if stripped.startswith(start):
                line = replacement
        for prefix in OPT_IN_PREFIXES:
            if stripped.startswith(prefix):
                line = stripped[2:]  # drop the leading "# "
                break
        key, sep, value = line.partition("=")
        if sep and not line.lstrip().startswith("#"):
            if key == "KEYCLOAK_ADMIN_PASSWORD" and PLACEHOLDER in value:
                line = f"{key}={keycloak_password}"
            elif key == "AUTH_DEV_SECRET":
                line = f"{key}={dev_signing_key}"
            elif key == "AUTH_MODE":
                line = f"{key}={auth_mode}"
            elif PLACEHOLDER in value:
                line = f"{key}={value.replace(PLACEHOLDER, db_password)}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--example", type=Path, default=REPO_ROOT / ".env.example")
    parser.add_argument("--output", type=Path, default=REPO_ROOT / ".env")
    parser.add_argument(
        "--auth", choices=("dev", "oidc"), default="dev", help="API sign-in mode (default: dev)"
    )
    parser.add_argument("--force", action="store_true", help="replace an existing .env")
    args = parser.parse_args(argv)

    if args.output.exists() and not args.force:
        print(
            f"{args.output} already exists, so I left it alone. Use --force to replace it.",
            file=sys.stderr,
        )
        return 1
    if not args.example.exists():
        print(f"Cannot find {args.example}.", file=sys.stderr)
        return 2

    text = build_env(args.example.read_text(encoding="utf-8"), auth_mode=args.auth)
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Created {args.output} with new random passwords (not shown).")
    print(
        f"API sign-in mode: {args.auth}"
        + (" (local signed tokens; see scripts/dev_token.py)" if args.auth == "dev" else "")
    )
    print("Next: docker compose up -d db")
    return 0


if __name__ == "__main__":
    sys.exit(main())
